-- 회원 연락처를 문자를 보낼 때와 같은 꼴(숫자만 남긴 국내 번호)로 바꾼다(be #66). 가입이 이제 이 꼴로 저장하므로,
-- 그 전에 입력한 꼴 그대로 저장된 연락처(010-1234-5678, +82 10-1234-5678 등)도 같은 꼴로 맞춘다.
-- 규칙은 PhoneNumbers.normalize와 같다 — 숫자만 남기고, 82로 시작하면 82를 떼고 앞에 0을 붙인다. 82 바로 뒤가 0이면
-- 그 0을 그대로 쓴다(+82 010-…이 0010…이 되지 않게). 그래서 맨 앞의 82 또는 820을 0 하나로 바꾼다.
-- 이미 이 꼴인 연락처(01012345678)는 바뀌지 않는다.
UPDATE member
SET phone = REGEXP_REPLACE(REGEXP_REPLACE(phone, '[^0-9]', ''), '^820?', '0');
